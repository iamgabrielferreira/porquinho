CREATE DATABASE porquinho;
USE porquinho;

CREATE TABLE usuario (
id INT AUTO_INCREMENT PRIMARY KEY,
nome VARCHAR (100) NOT NULL,
cod_pais VARCHAR (5) NOT NULL DEFAULT '+55',
telefone VARCHAR (15) NOT NULL,
email VARCHAR (254) NOT NULL UNIQUE,
senha_hash VARCHAR (255) NOT NULL,
dt_acesso DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE deposito (
id INT AUTO_INCREMENT PRIMARY KEY,
fk_usuario INT NOT NULL,
valor DECIMAL (10,2) NOT NULL CHECK (valor > 0),
dt_deposito DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

CONSTRAINT fk_deposito_usuario
FOREIGN KEY (fk_usuario) REFERENCES usuario (id)
	ON DELETE CASCADE
);

CREATE TABLE gasto (
id INT AUTO_INCREMENT PRIMARY KEY,
fk_usuario INT NOT NULL,
descricao VARCHAR (100) NOT NULL,
valor DECIMAL (10,2) NOT NULL CHECK (valor > 0),
dt_gasto DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

CONSTRAINT fk_gasto_usuario
FOREIGN KEY (fk_usuario) REFERENCES usuario(id)
	ON DELETE CASCADE
);


